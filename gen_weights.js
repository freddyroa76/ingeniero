const mapNps = (n) => {
  const s = String(n);
  if (s === '0.5') return '1/2';
  if (s === '0.75') return '3/4';
  if (s === '1.25') return '1-1/4';
  if (s === '1.5') return '1-1/2';
  if (s === '2.5') return '2-1/2';
  if (s === '3.5') return '3-1/2';
  return s;
};

