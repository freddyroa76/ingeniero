def normalize_key(key):
    mapping = {
        "0.5": "1/2",
        "0.75": "3/4",
        "1.25": "1-1/4",
        "1.5": "1-1/2",
        "2.5": "2-1/2",
        "3.5": "3-1/2"
    }
    return mapping.get(key, key)

weights_db = {}
conversion = 1.4881639

# 3. Generate Full DB
for size, data in pipe_dimensions.items():
    OD = data["OD"]
    new_size_key = normalize_key(size)
    weights_db[new_size_key] = {}
    
    for sch, t in data["schedules"].items():
        if t <= 0: continue
        lbft = 10.69 * (OD - t) * t
        kgm = lbft * conversion
        
        weights_db[new_size_key][sch] = {
            "kgm": round(kgm, 2),
            "lbft": round(lbft, 2)
        }

# 4. Apply Overrides
lines = user_raw_data.strip().split('\n')
for line in lines:
    parts = line.split('\t')
    if len(parts) < 6:
        continue
    
    nps_raw = parts[0].replace('"', '').strip()
    sch_raw = parts[2].strip()
    # Handle weird number formats just in case
    try:
        lbft = float(parts[4])
        kgm = float(parts[5])
    except ValueError:
        continue

    # Parse schedules (handle slashes)
    schedules = [s.strip() for s in sch_raw.split('/')]

    if nps_raw not in weights_db:
        # Should imply it was missing from pipe_dimensions? 
        # But all listed NPS are in pipe_dimensions.
        weights_db[nps_raw] = {}

    for s in schedules:
        # Override specifically this schedule
        weights_db[nps_raw][s] = {
            "kgm": kgm,
            "lbft": lbft
        }

print("      const WEIGHTS = " + json.dumps(weights_db, indent=2) + ";")
